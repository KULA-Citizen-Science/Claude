#!/usr/bin/env python3
"""Regenerate web/js/art.js from the Kotlin SceneArt catalog (single source of truth).

Usage: python3 web/tools/gen-art.py   (run from the repo root)
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "core/src/main/kotlin/com/kula/nextquest/domain/art/SceneArt.kt"
OUT = ROOT / "web/js/art.js"

section = None
cur = None
maps = {"traps": {}, "emblems": {}}
for line in SRC.read_text().splitlines():
    if "val traps" in line:
        section = "traps"
    elif "val emblems" in line:
        section = "emblems"
    m = re.search(r'"([A-Za-z]+)" to Sprite\(', line)
    if m and section:
        cur = m.group(1)
        maps[section][cur] = []
        continue
    m = re.search(r'^\s*"([.KWDGCMLPS]+)",?\s*$', line)
    if m and cur and section:
        maps[section][cur].append(m.group(1))

header = (
    "// GENERATED by web/tools/gen-art.py from core/.../domain/art/SceneArt.kt — do not edit.\n"
    "// Palette: . transparent, K ink, W cream, D danger, G gold, C cyan, M magenta, L lime,\n"
    "// P panel purple, S shadow purple. Mapped to colours in render.js.\n"
)
body = "export const TRAPS = " + json.dumps(maps["traps"], indent=2) + ";\n\n"
body += "export const EMBLEMS = " + json.dumps(maps["emblems"], indent=2) + ";\n"
OUT.write_text(header + body)
print(f"wrote {OUT.relative_to(ROOT)}: {len(maps['traps'])} traps, {len(maps['emblems'])} emblems")
